#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const SOURCE_PATH = join(ROOT, "tools/dev/member-colors.json");
const OUTPUT_PATH = join(ROOT, "src/client/styles/member-colors.generated.css");

const EXPECTED_KEYS = [
  "blue",
  "sky",
  "cyan",
  "teal",
  "green",
  "lime",
  "yellow",
  "amber",
  "orange",
  "red",
  "rose",
  "pink",
  "fuchsia",
  "purple",
  "violet",
  "indigo",
];

// The approved base shade is 500 at L=0.58. Every other shade keeps its
// chroma and hue and substitutes the old application's documented lightness.
const LIGHTNESS_BY_STEP = new Map([
  [100, 0.93],
  [200, 0.87],
  [300, 0.78],
  [400, 0.68],
  [500, 0.58],
  [600, 0.5],
  [700, 0.42],
  [800, 0.35],
  [900, 0.28],
]);

const BLACK = { l: 0, c: 0, h: 0 };
const WHITE = { l: 1, c: 0, h: 0 };
const MIN_CONTRAST_RATIO = 4.5;

function assertPlainObject(value, label) {
  if (value === null || Array.isArray(value) || typeof value !== "object") {
    throw new TypeError(`${label} must be an object`);
  }
}

function assertExactKeys(value, keys, label) {
  const actual = Object.keys(value);
  if (actual.length !== keys.length || actual.some((key, index) => key !== keys[index])) {
    throw new TypeError(`${label} must contain exactly ${keys.join(", ")} in that order`);
  }
}

export function validatePalette(palette) {
  if (!Array.isArray(palette) || palette.length !== EXPECTED_KEYS.length) {
    throw new TypeError(`member-colors.json must contain exactly ${EXPECTED_KEYS.length} entries`);
  }

  palette.forEach((entry, index) => {
    const expectedKey = EXPECTED_KEYS[index];
    assertPlainObject(entry, `palette entry ${index}`);
    assertExactKeys(entry, ["key", "name", "base500"], `palette entry ${index}`);
    if (entry.key !== expectedKey || entry.name !== expectedKey) {
      throw new TypeError(`palette entry ${index} must use key and name ${expectedKey}`);
    }

    assertPlainObject(entry.base500, `${expectedKey}.base500`);
    assertExactKeys(entry.base500, ["l", "c", "h"], `${expectedKey}.base500`);
    const { l, c, h } = entry.base500;
    if (![l, c, h].every(Number.isFinite)) {
      throw new TypeError(`${expectedKey}.base500 must contain finite OKLCH numbers`);
    }
    if (l !== LIGHTNESS_BY_STEP.get(500)) {
      throw new RangeError(`${expectedKey}.base500.l must be ${LIGHTNESS_BY_STEP.get(500)}`);
    }
    if (c < 0 || h < 0 || h >= 360) {
      throw new RangeError(`${expectedKey}.base500 chroma or hue is outside the supported range`);
    }
  });

  return palette;
}

function oklchToClippedLinearSrgb({ l, c, h }) {
  const hueRadians = (h * Math.PI) / 180;
  const a = c * Math.cos(hueRadians);
  const b = c * Math.sin(hueRadians);
  const lPrime = l + 0.3963377774 * a + 0.2158037573 * b;
  const mPrime = l - 0.1055613458 * a - 0.0638541728 * b;
  const sPrime = l - 0.0894841775 * a - 1.291485548 * b;
  const lab = [lPrime ** 3, mPrime ** 3, sPrime ** 3];
  const rgb = [
    4.0767416621 * lab[0] - 3.3077115913 * lab[1] + 0.2309699292 * lab[2],
    -1.2684380046 * lab[0] + 2.6097574011 * lab[1] - 0.3413193965 * lab[2],
    -0.0041960863 * lab[0] - 0.7034186147 * lab[1] + 1.707614701 * lab[2],
  ];
  return rgb.map((channel) => Math.min(1, Math.max(0, channel)));
}

function relativeLuminance(oklch) {
  const [red, green, blue] = oklchToClippedLinearSrgb(oklch);
  return 0.2126 * red + 0.7152 * green + 0.0722 * blue;
}

function contrastRatio(first, second) {
  const lighter = Math.max(relativeLuminance(first), relativeLuminance(second));
  const darker = Math.min(relativeLuminance(first), relativeLuminance(second));
  return (lighter + 0.05) / (darker + 0.05);
}

function selectForeground(base500, key) {
  const blackContrast = contrastRatio(base500, BLACK);
  const whiteContrast = contrastRatio(base500, WHITE);
  const foreground = blackContrast >= whiteContrast ? BLACK : WHITE;
  const contrast = Math.max(blackContrast, whiteContrast);
  if (contrast < MIN_CONTRAST_RATIO) {
    throw new RangeError(`${key} has no generated foreground meeting ${MIN_CONTRAST_RATIO}:1`);
  }
  return foreground;
}

function formatOklch({ l, c, h }) {
  return `oklch(${l} ${c} ${h})`;
}

export function generateMemberColorsCss(palette) {
  validatePalette(palette);
  const lines = [
    "/* AUTO-GENERATED by tools/dev/generate-member-colors.mjs.",
    " * Edit tools/dev/member-colors.json and run the generator; do not edit this file.",
    " *",
    " * Scale contract: 100-900 use fixed lightness values; every hue keeps the approved",
    " * base-500 chroma and hue. The companion foreground is the higher-contrast choice",
    " * of black or white against 500, measured from clipped linear sRGB at WCAG 4.5:1.",
    " */",
    // Static theme variables remain available to runtime-composed surfaces such as
    // multi-member calendar bands, in addition to generating Tailwind utilities.
    "@theme static {",
  ];

  for (const entry of palette) {
    for (const [step, lightness] of LIGHTNESS_BY_STEP) {
      lines.push(
        `  --color-member-${entry.name}-${step}: ${formatOklch({
          l: lightness,
          c: entry.base500.c,
          h: entry.base500.h,
        })};`
      );
    }
    const foreground = selectForeground(entry.base500, entry.key);
    lines.push(`  --color-member-${entry.name}-foreground: ${formatOklch(foreground)};`);
  }

  lines.push("}", "");
  return lines.join("\n");
}

function loadPalette() {
  return JSON.parse(readFileSync(SOURCE_PATH, "utf8"));
}

function run() {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--check") || args.length > 1) {
    console.error("Usage: node tools/dev/generate-member-colors.mjs [--check]");
    process.exitCode = 2;
    return;
  }

  const expected = generateMemberColorsCss(loadPalette());
  if (args[0] === "--check") {
    let actual;
    try {
      actual = readFileSync(OUTPUT_PATH, "utf8");
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
      actual = null;
    }
    if (actual !== expected) {
      console.error(
        "src/client/styles/member-colors.generated.css has drifted; run npm run generate:member-colors."
      );
      process.exitCode = 1;
      return;
    }
    console.log("Member colour scales are up to date.");
    return;
  }

  writeFileSync(OUTPUT_PATH, expected, "utf8");
  console.log("Generated src/client/styles/member-colors.generated.css.");
}

const isMain =
  process.argv[1] !== undefined && pathToFileURL(process.argv[1]).href === import.meta.url;
if (isMain) run();
