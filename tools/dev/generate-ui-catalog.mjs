#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";
import { format } from "prettier";

/** Actual exported API inventory; prop contracts remain in the linked TypeScript sources. */
export function renderCatalog(root = process.cwd()) {
  const parse = (name) =>
    ts.createSourceFile(
      name,
      readFileSync(resolve(root, name), "utf8"),
      ts.ScriptTarget.Latest,
      true
    );
  const rows = [];
  for (const statement of parse("src/client/ui.ts").statements) {
    if (!ts.isExportDeclaration(statement) || !statement.moduleSpecifier) continue;
    const file = `src/client/${statement.moduleSpecifier.text.replace(/^\.\//, "")}.tsx`;
    const names = [];
    for (const declaration of parse(file).statements) {
      if (
        ts.isExportDeclaration(declaration) &&
        declaration.exportClause &&
        ts.isNamedExports(declaration.exportClause)
      ) {
        names.push(...declaration.exportClause.elements.map((element) => element.name.text));
      } else if (
        declaration.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword) &&
        declaration.name
      )
        names.push(declaration.name.text);
    }
    rows.push(
      `| ${names
        .sort()
        .map((name) => `\`${name}\``)
        .join(", ")} | [${file}](${file}) |`
    );
  }
  return `# Shared UI catalog\n\nGenerated by \`npm run generate:ui-catalog\`; checked by \`npm run check:ui-catalog\`.\nImport shared UI from \`@/ui\`. Read [the component contract](docs/ui/component-contract.md) and [the style guide](docs/development/style-guide.md) before adding a pattern.\n\nThis export inventory links to the maintained prop types and variants. It does not duplicate native React props or promise uninstalled primitives.\n\n| Exports | Source and prop contracts |\n| --- | --- |\n${rows.join("\n")}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const expected = await format(renderCatalog(), { parser: "markdown" });
  if (process.argv.includes("--check")) {
    if (readFileSync("COMPONENTS.md", "utf8") !== expected)
      throw new Error("UI catalog drift; run npm run generate:ui-catalog");
    console.log("UI catalog matches the shared exports");
  } else writeFileSync("COMPONENTS.md", expected);
}
